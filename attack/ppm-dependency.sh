#!/usr/bin/env bash
# 🍍 Pineapple Pizza Mafia act 2: the poisoned dependency.
#
# The app's code is clean. The PPM publishes a new version of a package the
# app depends on, crust-receipt, with a surprise: a Pineapple Tax on every
# order. A routine dependency bump pulls it in. Here that means building the
# poisoned 1.1.0 wheel into the local index and repinning app/requirements.txt
# to it, the way `uv lock --upgrade` would after the release landed.
#
#   attack/ppm-dependency.sh          publish 1.1.0 and repin the app to it
#   attack/ppm-dependency.sh --undo   rebuild the clean pin (packages/build-wheels.sh)
#   attack/ppm-dependency.sh --show   show the poisoned package's diff from clean
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INDEX="$ROOT/app/wheels"
log() { printf '\033[1;35m🍍 %s\033[0m\n' "$*" >&2; }

case "${1:-}" in
  --show) diff -u "$ROOT/packages/crust-receipt/src/crust_receipt/__init__.py" \
                  "$ROOT/attack/ppm-receipt/src/crust_receipt/__init__.py" || true; exit 0 ;;
  --undo) log "restoring the clean pin"; exec "$ROOT/packages/build-wheels.sh" ;;
esac

command -v uv >/dev/null || { echo "error: uv is required" >&2; exit 1; }
export SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-1700000000}"
mkdir -p "$INDEX"
log "Building the poisoned crust-receipt 1.1.0 into the index"
( cd "$ROOT/attack/ppm-receipt" && uv build --wheel -o "$INDEX" >/dev/null 2>&1 )
WHL="$INDEX/crust_receipt-1.1.0-py3-none-any.whl"
H="$(shasum -a 256 "$WHL" | cut -d' ' -f1)"
printf '# Generated by packages/build-wheels.sh. The app installs crust-receipt\n# from the local wheel index, pinned to this exact wheel by hash.\ncrust-receipt==1.1.0 --hash=sha256:%s\n' "$H" > "$ROOT/app/requirements.txt"
log "repinned app/requirements.txt to crust-receipt==1.1.0 (sha256:${H:0:12}…). The PPM sends their regards."
log "rebuild and redeploy the app to serve it"
