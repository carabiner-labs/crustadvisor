#!/usr/bin/env bash
# Build the clean crust-receipt wheel into the local package index and pin it,
# by exact version and wheel hash, in app/requirements.txt. Run before the
# talk, the way build-base is. The dependency gate reads app/requirements.txt;
# the app image installs from it with --require-hashes.
#
#   packages/build-wheels.sh
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
INDEX="$ROOT/build/pkgindex"
log() { printf '\033[1;36m==> %s\033[0m\n' "$*" >&2; }
command -v uv >/dev/null || { echo "error: uv is required" >&2; exit 1; }

mkdir -p "$INDEX"
log "Building crust-receipt (clean) into $INDEX"
( cd "$ROOT/packages/crust-receipt" && uv build --wheel -o "$INDEX" >/dev/null 2>&1 )
WHL="$(ls -t "$INDEX"/crust_receipt-1.0.0-py3-none-any.whl | head -1)"
H="$(shasum -a 256 "$WHL" | cut -d' ' -f1)"
printf '# Generated by packages/build-wheels.sh. The app installs crust-receipt\n# from the local wheel index, pinned to this exact wheel by hash.\ncrust-receipt==1.0.0 --hash=sha256:%s\n' "$H" > "$ROOT/app/requirements.txt"
log "pinned crust-receipt==1.0.0 (sha256:${H:0:12}…) in app/requirements.txt"
